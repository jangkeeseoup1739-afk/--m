// Generate the complete LifeChartReport
export function buildLifeChartReport(
  input: BirthInput,
  saju: SajuPillars,
  fiveElements: FiveElementsCount,
  tenGods: TenGodsDistribution,
  daeunList: DaeunPeriod[],
  annualLuckList: AnnualLuck[],
  westernAstrology: WesternAstrologyData,
  thaiAstrology: ThaiAstrologyData
): LifeChartReport {
  const steps = generate13Steps(
    input,
    saju,
    fiveElements,
    tenGods,
    daeunList,
    annualLuckList,
    westernAstrology,
    thaiAstrology
  );

  const dmDesc = DAY_MASTER_DESCRIPTIONS[saju.dayMaster] || DAY_MASTER_DESCRIPTIONS['甲'];
  const domElem = ELEMENT_TRAITS[fiveElements.dominant];

  const keywords = [
    dmDesc.title.split(' ')[0] + ' ' + dmDesc.title.split(' ')[1],
    `${domElem.nameKr}의 생명력`,
    westernAstrology.sunSign.split(' ')[0],
    `수호: ${thaiAstrology.guardianPlanet.split(' ')[1] || '태양'}`,
    `조화지수 ${fiveElements.balanceScore}점`,
  ];

  const keyHeadline = `${input.name}님의 인생차트는 [${dmDesc.title}]의 굳건한 본성에 [${domElem.nameKr}]의 활력이 결합된, 흔들리지 않는 중심과 유연한 지혜의 조화입니다.`;

  return {
    id: `report_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
    createdAt: new Date().toISOString(),
    birth: input,
    saju,
    fiveElements,
    tenGods,
    daeunList,
    annualLuckList,
    westernAstrology,
    thaiAstrology,
    keywords,
    keyHeadline,
    steps,
  };
}
